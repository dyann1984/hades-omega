export type TKey = keyof typeof DICT['es']
export function translate(lang: Lang, key: TKey): string { return DICT[lang][key] ?? DICT.es[key] ?? key }
export function useLang(): Lang { return useSyncExternalStore(subscribe, getLang, getLang) }
export function useT(): (key: TKey) => string { const lang = useLang(); return key => translate(lang, key) }
